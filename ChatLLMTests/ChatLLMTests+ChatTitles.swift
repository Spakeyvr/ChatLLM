import Testing
import Foundation
import SwiftData
import FoundationModels
@testable import ChatLLM

extension ChatLLMTests {

    // MARK: - Naming triggers

    @Test func chatIsNamedOnALaterTurnWhenTheFirstReplyWasStopped() async throws {
        let viewModel = try makeTitleTestViewModel(turns: [
            (.user, "SwiftData migration crashes on launch", true),
            (.assistant, "Let's look at", false)
        ])

        let turn = try #require(viewModel.prepareUserMessageForSend("Here is the stack trace"))
        #expect(turn.needsAutoNaming)

        await viewModel.finishAutoNamingIfNeeded(turn.needsAutoNaming)

        #expect(viewModel.conversation.title == "SwiftData migration crashes on launch")
        #expect(viewModel.conversation.hasAutoGeneratedTitle)
    }

    @Test func draftCreatedInAnotherLanguageIsStillNamed() async throws {
        let currentDefault = String(localized: "New Chat", bundle: .appLocalized)
        let otherDefault = try #require(["New Chat", "Neuer Chat", "Nuevo chat"].first { $0 != currentDefault })
        let viewModel = try makeTitleTestViewModel(
            title: otherDefault,
            turns: [(.user, "Plan a Vienna weekend", true)]
        )

        await viewModel.generateChatTitle()

        #expect(viewModel.conversation.title == "Plan a Vienna weekend")
        #expect(viewModel.conversation.hasAutoGeneratedTitle)
    }

    @Test func renamingWhileATitleIsGeneratingKeepsTheUsersName() throws {
        let viewModel = try makeTitleTestViewModel(turns: [
            (.user, "Plan a Vienna weekend", true)
        ])

        // The user renames the chat while the model is still producing a title.
        viewModel.conversation.title = "Trip Ideas"
        viewModel.applyAutoGeneratedTitle("Vienna Weekend Itinerary")

        #expect(viewModel.conversation.title == "Trip Ideas")
        #expect(!viewModel.conversation.hasAutoGeneratedTitle)
    }

    @Test func vagueOpenerDefersNamingUntilTheTopicIsKnown() async throws {
        let viewModel = try makeTitleTestViewModel(turns: [
            (.user, "hi", true),
            (.assistant, "Hello! How can I help?", true)
        ])

        await viewModel.generateChatTitle()

        #expect(AppLanguage.isDefaultConversationTitle(viewModel.conversation.title))
        #expect(!viewModel.conversation.hasAutoGeneratedTitle)

        let turn = try #require(viewModel.prepareUserMessageForSend("How do I cook risotto"))
        #expect(turn.needsAutoNaming)
        await viewModel.finishAutoNamingIfNeeded(turn.needsAutoNaming)

        #expect(viewModel.conversation.title == "How do I cook risotto")
    }

    @Test func manuallyRenamedChatIsNotRenamedOnLaterTurns() throws {
        let viewModel = try makeTitleTestViewModel(
            title: "My notes",
            turns: [(.user, "hi", true), (.assistant, "Hello!", true)]
        )

        let turn = try #require(viewModel.prepareUserMessageForSend("How do I cook risotto"))

        #expect(!turn.needsAutoNaming)
    }

    // MARK: - Title source

    @Test func titleSourceTreatsGreetingsAndHelpRequestsAsVague() {
        for opener in ["hi", "Hey there!", "quick question", "Can you help me with something?", "Hallo", "hola, ¿qué tal?"] {
            #expect(ChatTitleSource.isTooVagueToName(opener), "\(opener)")
        }
        for topic in ["Kubernetes", "How do I cook risotto", "What's a monad?"] {
            #expect(!ChatTitleSource.isTooVagueToName(topic), "\(topic)")
        }
    }

    @Test func titleSourceStopsDeferringAfterThreeVagueTurns() {
        #expect(ChatTitleSource(userMessages: ["hi", "hello"], latestReply: nil).shouldDeferNaming)
        #expect(!ChatTitleSource(userMessages: ["hi", "hello", "hey"], latestReply: nil).shouldDeferNaming)
    }

    @Test func titlePromptIncludesTheLatestFinishedReplyAndSkipsFailedOnes() throws {
        let conversation = Conversation(title: "New Chat")
        let messages = [
            ChatLLM.Message(role: .user, text: "Compare these chips", order: 0, conversation: conversation, isFinal: true),
            ChatLLM.Message(role: .assistant, text: "The M4 is faster than the M3.", order: 1,
                            conversation: conversation, isFinal: true),
            ChatLLM.Message(role: .user, text: "And battery life?", order: 2, conversation: conversation, isFinal: true),
            ChatLLM.Message(role: .assistant, text: "Partial", order: 3, conversation: conversation, isFinal: false)
        ]

        let source = try #require(ChatTitleSource(messages: messages))

        #expect(source.userMessages == ["Compare these chips", "And battery life?"])
        #expect(source.latestReply == "The M4 is faster than the M3.")
        #expect(source.prompt == """
        User:
        Compare these chips
        And battery life?

        Assistant:
        The M4 is faster than the M3.
        """)
    }

    @Test func titlePromptTruncatesLongPastes() {
        let source = ChatTitleSource(
            userMessages: [String(repeating: "x", count: 2_000)],
            latestReply: String(repeating: "y", count: 2_000)
        )

        #expect(source.prompt.filter { $0 == "x" }.count == ChatTitleSource.maxUserCharacters)
        #expect(source.prompt.filter { $0 == "y" }.count == ChatTitleSource.maxReplyCharacters)
    }

    // MARK: - Model output cleanup

    @Test func generatedTitleCleanupRemovesFormattingInsteadOfRejecting() {
        #expect(ChatViewModel.sanitizedGeneratedTitle("\"SwiftData Migration Error\"") == "SwiftData Migration Error")
        #expect(ChatViewModel.sanitizedGeneratedTitle("Title: Vienna Weekend Itinerary.") == "Vienna Weekend Itinerary")
        #expect(ChatViewModel.sanitizedGeneratedTitle("**Compare M3 and M4?**") == "Compare M3 and M4")
        #expect(ChatViewModel.sanitizedGeneratedTitle("  Fix   JSON\nParsing Bug ") == "Fix JSON")
    }

    @Test func generatedTitleCleanupRejectsPlaceholderTitles() {
        #expect(ChatViewModel.sanitizedGeneratedTitle("") == nil)
        #expect(ChatViewModel.sanitizedGeneratedTitle("\"\"") == nil)
        #expect(ChatViewModel.sanitizedGeneratedTitle("New Chat") == nil)
        #expect(ChatViewModel.sanitizedGeneratedTitle("Untitled Conversation") == nil)
    }

    @Test func generatedTitleCleanupShortensAtAWordBoundary() throws {
        let title = try #require(ChatViewModel.sanitizedGeneratedTitle(
            "Comparing Every Apple Silicon Generation For Machine Learning Workloads"
        ))

        #expect(title == "Comparing Every Apple Silicon Generation For…")
        #expect(title.count <= 50)
    }

    @Test func wordBasedTitleSkipsPastedCodeAndMarkdown() {
        #expect(ChatViewModel.fallbackTitle(from: "Fix this:\n```python\nprint(1)\n```") == "Fix this")
        #expect(ChatViewModel.fallbackTitle(from: "```swift\nlet x = 1\n```\nWhy does this crash?") == "Why does this crash")
        #expect(ChatViewModel.fallbackTitle(from: "## **Plan** a trip to Vienna in May with friends") == "Plan a trip to Vienna in")
        #expect(ChatViewModel.fallbackTitle(from: "Why does `fetch()` fail") == "Why does fetch() fail")
        #expect(ChatViewModel.fallbackTitle(from: "- buy milk\n- call mom") == "buy milk call mom")
        // A message that is only code is named after the code, not its language tag.
        #expect(ChatViewModel.fallbackTitle(from: "```swift\nfunc loadModel() async throws\n```") == "func loadModel() async throws")
        #expect(ChatViewModel.fallbackTitle(from: "```") == nil)
    }

    @Test func wordBasedTitleShortensAtAWordBoundary() throws {
        let title = try #require(ChatViewModel.fallbackTitle(
            from: "Internationalization considerations for multilingual applications development"
        ))
        #expect(title.hasSuffix("…"))
        #expect(!title.contains("..."))
        #expect(title.count <= 50)
    }

    @Test func titleGenerationDoesNotRetryGuardrailViolations() {
        let violation = LanguageModelError.GuardrailViolation(debugDescription: "blocked")

        #expect(!ChatViewModel.shouldRetryTitleGeneration(after: LanguageModelError.guardrailViolation(violation)))
        #expect(ChatViewModel.shouldRetryTitleGeneration(after: CancellationError()))
    }

    // MARK: - Helpers

    /// MLX keeps naming deterministic: it uses the word-based title instead of Apple Intelligence.
    private func makeTitleTestViewModel(
        title: String = "New Chat",
        turns: [(MessageRole, String, Bool)]
    ) throws -> ChatViewModel {
        let schema = Schema([Conversation.self, ChatLLM.Message.self, MessageAttachment.self])
        let container = try ModelContainer(
            for: schema,
            configurations: [ModelConfiguration(isStoredInMemoryOnly: true)]
        )
        let context = ModelContext(container)
        let conversation = Conversation(title: title)
        context.insert(conversation)
        conversation.messages = turns.enumerated().map { index, turn in
            ChatLLM.Message(role: turn.0, text: turn.1, order: index, conversation: conversation, isFinal: turn.2)
        }
        try context.save()

        let bridge = makeBackendBridge()
        bridge.selectedBackend = .mlx
        return ChatViewModel(
            generator: TestLLMGenerator(),
            context: context,
            conversation: conversation,
            backendBridge: bridge,
            defaults: testEnvironment.defaults,
            observesAPIKeyChanges: false
        )
    }
}
